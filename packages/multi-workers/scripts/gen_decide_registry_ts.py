#!/usr/bin/env python3
"""Generate ``packages/coding-agent/.../shared/decide-registry.generated.ts``.

The registry (``decision_points.registry_snapshot``) is the single authority for
which state fields a dp requires; ``decision_context.CONTEXT_SLOTS`` is the
authority for the ``context`` slots a dp may emit. The TS producers may not keep
a second hand-written copy, so this script renders both into a checked-in
module and ``test_decide_registry_ts_lock.py`` fails on any byte drift.

Usage::

    python scripts/gen_decide_registry_ts.py            # write the file
    python scripts/gen_decide_registry_ts.py --check    # exit 1 on drift
    python scripts/gen_decide_registry_ts.py --stdout   # print, touch nothing

Deterministic by construction: points are sorted by id, fields keep the
``REQUIRED_STATE_FIELDS`` order, slots keep ``decision_context.SLOT_ORDER``, and
the output is ASCII-safe UTF-8 JSON-ish text with a stable 2-space indent.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

_HERE = pathlib.Path(__file__).resolve().parent
_MW_ROOT = _HERE.parent
_REPO_ROOT = _MW_ROOT.parent.parent
if str(_MW_ROOT) not in sys.path:
    sys.path.insert(0, str(_MW_ROOT))

import decision_context  # noqa: E402
import decision_points  # noqa: E402

#: Target module (repo-relative, also the drift-lock path).
OUTPUT_RELATIVE_PATH = pathlib.Path(
    "packages/coding-agent/src/extensions/agent-team-loop/shared/decide-registry.generated.ts"
)

GENERATED_HEADER = (
    "// @generated by packages/multi-workers/scripts/gen_decide_registry_ts.py — do not edit\n"
    "// Regenerate: cd packages/multi-workers && python scripts/gen_decide_registry_ts.py\n"
    "// Drift lock: test_decide_registry_ts_lock.py fails when this file is stale.\n"
)


def _ts_string(text: str) -> str:
    """JSON string literal (double quotes) — valid TS, stable bytes."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(snapshot: dict | None = None) -> str:
    """Render the module text for ``snapshot`` (default: live registry)."""
    doc = decision_points.registry_snapshot() if snapshot is None else snapshot
    points = sorted(doc["points"], key=lambda point: str(point["id"]))
    lines: list[str] = [
        GENERATED_HEADER.rstrip("\n"),
        "",
        "/** Required dp state fields + context slots, generated from the Python registry. */",
        "export interface DecideRegistryEntry {",
        "\tquestionsVersion: string;",
        "\trequiredStateFields: { name: string; type: string }[];",
        "\tcontextSlots: string[];",
        "}",
        "",
        "export const DECIDE_REGISTRY: Record<string, DecideRegistryEntry> = {",
    ]
    for point in points:
        dp_id = str(point["id"])
        lines.append(f"\t{_ts_string(dp_id)}: {{")
        lines.append(f"\t\tquestionsVersion: {_ts_string(str(point['questions_version']))},")
        fields = point.get("required_state_fields") or []
        if not fields:
            lines.append("\t\trequiredStateFields: [],")
        else:
            lines.append("\t\trequiredStateFields: [")
            for field_spec in fields:
                name = _ts_string(str(field_spec["name"]))
                kind = _ts_string(str(field_spec["type"]))
                lines.append(f"\t\t\t{{ name: {name}, type: {kind} }},")
            lines.append("\t\t],")
        slots = decision_context.slot_names_for(dp_id)
        if not slots:
            lines.append("\t\tcontextSlots: [],")
        else:
            rendered = ", ".join(_ts_string(slot) for slot in slots)
            lines.append(f"\t\tcontextSlots: [{rendered}],")
        lines.append("\t},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def output_path() -> pathlib.Path:
    return _REPO_ROOT / OUTPUT_RELATIVE_PATH


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    parser.add_argument("--stdout", action="store_true", help="print, do not write")
    args = parser.parse_args(argv)

    text = render()
    if args.stdout:
        sys.stdout.write(text)
        return 0
    path = output_path()
    if args.check:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            sys.stderr.write(f"stale generated registry: {OUTPUT_RELATIVE_PATH}\n")
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {OUTPUT_RELATIVE_PATH} ({len(text)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
