"""T-21 / mw-gate-verdict-hardening: the IN-3 queue-shape replay (AC-019, AC-023).

The 2026-10-10 incident rebuilt `.agenticdoc/_workers.parallel` as 252 rows in
one second because a long-lived pi window ran a codec that could not read the
rows the other codec wrote (post-mortem §4.2): the rows on disk were 9 columns,
that window's parser accepted 7..8, `readAll()` therefore returned the empty
set, and `dispatchNewTasks` re-queued every `task.md` in the project.

This file replays the incident's *row shape* against the fixed codec. The
fixture is de-sensitised but column-faithful (see
`evidence/runs/t-21-integrity-report.md` §2 for provenance and sha256):

* every line carries the incident's burst second in `dispatched_at`;
* 9 columns, ` | ` separator, `Z` (TS) and `+00:00` (Python) timestamps;
* generated by `evidence/scripts/t21-make-in3-fixture.py`.

Run: cd packages/multi-workers && python -X utf8 -m pytest test_in3_queue_replay.py -q
"""

from __future__ import annotations

import pathlib
import sys

import pytest

sys.path.insert(0, str(pathlib.Path(__file__).parent))

import mw_common

FIXTURE = pathlib.Path(__file__).parent / "test" / "fixtures" / "in3-queue-9col-burst.txt"
BURST_SECOND = "2026-10-10T02:50:05"
# Snapshot size (the incident itself was 252 rows / 28 owners; 250 rows / 27
# owners were still readable in the live queue when the fixture was frozen).
FIXTURE_ROWS = 250
FIXTURE_OWNERS = 27

# The codec that lost the rows: `b8bc115ff^` `shared/worker-store.ts`
# (`WORKER_COLS = 8`, `if (parts.length !== 8 && parts.length !== 7) return undefined;`).
LEGACY_WORKER_COLS = 8


def legacy_parse(line: str) -> list[str] | None:
    """The pre-`b8bc115ff` reader, verbatim: silent `undefined` on 9 columns."""
    parts = [p.strip() for p in line.split("|")]
    if len(parts) != LEGACY_WORKER_COLS and len(parts) != LEGACY_WORKER_COLS - 1:
        return None
    return parts


def _lines() -> list[str]:
    return [line for line in FIXTURE.read_text(encoding="utf-8").splitlines() if line.strip()]


def _queue_root(tmp_path: pathlib.Path) -> pathlib.Path:
    root = tmp_path / ".agenticdoc"
    root.mkdir(parents=True, exist_ok=True)
    return root


def _write_queue(root: pathlib.Path, lines: list[str]) -> pathlib.Path:
    path = root / "_workers.parallel"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return path


def test_fixture_is_the_incident_shape() -> None:
    lines = _lines()
    assert len(lines) == FIXTURE_ROWS
    assert all(len(line.split("|")) == 9 for line in lines)

    cols = [[c.strip() for c in line.split("|")] for line in lines]
    assert all(c[5].startswith(BURST_SECOND) and c[5].endswith("Z") for c in cols)
    assert all(c[6].endswith("+00:00") for c in cols)
    assert {c[8] for c in cols} == {"manual"}

    owners = [c[4].split("/")[3] for c in cols]
    assert len(set(owners)) == FIXTURE_OWNERS
    # Pure ASCII owner grouping, no interleaving: the shape of a single scan.
    assert owners == sorted(owners)

    leaked = [
        line
        for line in lines
        if any(token in line for token in ("Multi-Workers", "E2Feature", "msc-", "wip-", "wjg-"))
    ]
    assert leaked == []


def test_current_codec_reads_every_incident_row(tmp_path: pathlib.Path) -> None:
    path = _write_queue(_queue_root(tmp_path), _lines())

    queue = mw_common.parse_workers_queue(path)

    assert queue["version"] == 1
    assert queue["unparsable"] == []
    assert len(queue["rows"]) == FIXTURE_ROWS
    # The predicate input `dispatchNewTasks` needs: a non-empty dispatched set.
    assert len({row["task_key"] for row in queue["rows"]}) == FIXTURE_ROWS


def test_legacy_codec_drops_every_incident_row() -> None:
    lines = _lines()

    readable = [line for line in lines if legacy_parse(line) is not None]

    # The incident mechanism, made executable: 9-column rows are invisible to
    # the pre-fix reader, so `readAll()` returns empty and every task.md looks
    # undispatched.
    assert len(readable) == 0
    assert len(lines) == FIXTURE_ROWS


def test_current_codec_also_reads_the_legacy_column_shape(tmp_path: pathlib.Path) -> None:
    # The old writer's own output (8 columns, no origin) must stay readable too:
    # tolerance has to cover both codecs, not just the new one.
    legacy_lines = [" | ".join(line.split("|")[:8]).rstrip() for line in _lines()]
    path = _write_queue(_queue_root(tmp_path), legacy_lines)

    queue = mw_common.parse_workers_queue(path)

    assert len(queue["rows"]) == FIXTURE_ROWS
    assert queue["unparsable"] == []
    # Python reports the absent column as empty (no normalisation to `manual`:
    # that happens in the TS store) and still groups each row under its key.
    assert {row["origin"] for row in queue["rows"]} == {""}
    assert all(mw_common.worker_owner_key(row).startswith("pk") for row in queue["rows"])
    assert not any(mw_common.worker_is_conductor(row) for row in queue["rows"])


def test_ten_column_row_is_counted_and_survives_all_three_writers(tmp_path: pathlib.Path) -> None:
    lines = _lines()
    bad = (
        f"inj-10col | pending | pi | timi | H:/proj/.agenticdoc/pk01/workers/inj/task.md | "
        f"{BURST_SECOND}.999Z | 2026-10-10T03:00:00+00:00 |  | manual | extra"
    )
    root = _queue_root(tmp_path)
    path = _write_queue(root, [*lines, bad])

    queue = mw_common.parse_workers_queue(path)
    assert len(queue["rows"]) == FIXTURE_ROWS
    assert [(u["line"], u["cols"]) for u in queue["unparsable"]] == [(FIXTURE_ROWS + 1, 10)]

    task_dir = root / "pk01" / "workers" / "pk01-t01"
    task_dir.mkdir(parents=True, exist_ok=True)
    (task_dir / "task.md").write_text("type: coding\n", encoding="utf-8")

    mw_common.update_status(root, "pk01-t01", "done")
    mw_common.archive_stale_entries(root)
    mw_common.upsert_worker_row(
        path,
        {
            "task_key": "brand-new",
            "status": "pending",
            "cli": "pi",
            "provider": "timi",
            "task_path": str(task_dir / "task.md"),
            "dispatched_at": f"{BURST_SECOND}.000Z",
            "updated_at": "2026-10-10T03:00:00+00:00",
            "model": "",
            "origin": "manual",
        },
    )

    after = path.read_text(encoding="utf-8").splitlines()
    assert len(after) == FIXTURE_ROWS + 2
    assert bad in after  # byte-identical slot, never rewritten, never deleted
    assert len(mw_common.parse_workers_queue(path)["unparsable"]) == 1


def test_doctor_reads_the_incident_shape_without_a_false_positive(tmp_path: pathlib.Path) -> None:
    root = tmp_path
    _write_queue(_queue_root(tmp_path), _lines())

    report = mw_common.doctor_report(root, fix=False, config=mw_common.load_providers(None))

    queue = report["queue"]
    assert queue["rows_total"] == FIXTURE_ROWS
    assert queue["unparsable_count"] == 0
    # Every row is terminal: the burst-shape criterion must stay silent
    # (it fires on a big queue that is *mostly non-terminal*).
    assert queue["non_terminal_count"] == 0
    assert queue["stale_count"] == 0
    assert queue["run_ledger_conflict"] == []
    assert [issue for issue in report["summary"]["issues"] if issue.startswith("queue-")] == []


@pytest.mark.parametrize("missing", [True, False])
def test_fixture_rows_are_terminal_and_keep_their_burst_stamp(tmp_path: pathlib.Path, missing: bool) -> None:
    lines = _lines()
    if missing:
        lines = [line for line in lines if "failed" not in line]
    path = _write_queue(_queue_root(tmp_path), lines)

    queue = mw_common.parse_workers_queue(path)

    assert len(queue["rows"]) == len(lines)
    assert {row["status"] for row in queue["rows"]} <= mw_common.RUN_TERMINAL_STATUSES
    assert all(row["dispatched_at"].startswith(BURST_SECOND) for row in queue["rows"])
