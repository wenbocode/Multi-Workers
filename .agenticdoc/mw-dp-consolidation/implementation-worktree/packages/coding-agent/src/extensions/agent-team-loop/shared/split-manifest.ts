/**
 * split-manifest.ts — the split manifest of one review task (design §2.3/§2.4,
 * card T-07, key `claim-driven-review-orchestration`).
 *
 * `evidence/split/review-<task>-manifest.json` is the ONLY truth of a split
 * dispatch: the merge gate reads the parent card's id set from here and from
 * nowhere else. RQ-1 §6.3 measured that the `card_sha256:` chain between a
 * parent card and its children does not exist today, so "the parent card was
 * edited after the split" is undetectable unless the manifest pins the bytes
 * it was built from:
 *
 * - `parentSha256` pins the parent card text,
 * - `units[*].sha256` pin every unit card text,
 * - `selfSha256` pins the manifest body itself (ids, units, packing, l0), so a
 *   hand-edited id set or unit boundary is detectable on its own.
 *
 * Build-time vs parse-time tolerance (P-048): the P-048 leniency belongs to the
 * PARSING seam (cards are user input). A manifest is generated by us with the
 * claims we just parsed, so an inconsistent id set is a programming error and
 * {@link buildSplitManifest} throws; {@link verifySplitManifest} is the
 * parse-time side and NEVER throws — it reports gaps and lets the merge gate
 * decide.
 *
 * Gap vocabulary (frozen, consumed by the merge gate):
 * `split:manifest:self-sha`, `split:manifest:parent-sha`,
 * `split:manifest:unit-sha:<taskKey>`,
 * `split:manifest:id-set:<missing|extra>:<id>`,
 * `split:manifest:packing-unit:<n>`.
 *
 * Contract: pure — no filesystem, no clock, no randomness, no model calls.
 * The same input always yields the same manifest bytes.
 *
 * Digest recipe: `sha256Hex` is sha256 over the **EOL-normalized** UTF-8 bytes
 * (CRLF → LF, then hash) in lower-case hex — the `card_sha256` convention, so
 * `parentSha256` compares verbatim with the `card_sha256:` header of the same
 * card (design §2.3). The recipe itself is not re-derived here: it is
 * `shared/card-digest.ts::sha256EolNormalizedBytes`, the TS mirror of
 * `mw_common.sha256_eol_normalized`, imported so a line-ending flip on checkout
 * is not drift while a one-character edit is. EOL normalization is a no-op on
 * the manifest body (`JSON.stringify` emits no CRLF) but the three pins still
 * share one recipe. Purity holds: importing `card-digest.ts` pulls only its
 * pure byte helpers; reading a card file stays the caller's job.
 */

import { sha256EolNormalizedBytes } from "./card-digest.ts";

/** One dispatch unit of the split: which claims it owns and which card body. */
export interface SplitUnitRef {
	/** 1-based unit index (`workers/<parent>-u<k>`). */
	k: number;
	/** Task key of the unit card (`<parent>-u<k>`). */
	taskKey: string;
	/** Claim ids owned by this unit, in packing order. */
	ids: string[];
	/** `Σ预算` of this unit, `manual` counted twice (`packClaims`). */
	budgetSum: number;
	/** Slot cost of this unit (`PackUnit.slots`). */
	slots: number;
	/** Write face of the unit card (`workers/<parent>-u<k>`). */
	writeFace: string;
	/** EOL-normalized sha256 of the unit card text ({@link sha256Hex}). */
	sha256: string;
}

/** One cluster -> unit mapping row: the evidence that a cluster stayed atomic. */
export interface SplitPackingRow {
	/** Claim ids the cluster covers. */
	cluster: string[];
	/** Target unit `k`. */
	unit: number;
	/** Why the cluster sits there (`struct-atomic` / `budget` / `locator` / `order`). */
	why: string;
}

/** L0 boundary: how many review asks exist, how many the split mapped. */
export interface SplitManifestL0 {
	asks: number;
	mapped: number;
	unmapped: string[];
}

/** The split manifest written to `evidence/split/review-<parent>-manifest.json`. */
export interface SplitManifest {
	v: 1;
	parent: string;
	mode: "plan" | "on";
	parentSha256: string;
	ids: string[];
	units: SplitUnitRef[];
	packing: SplitPackingRow[];
	l0: SplitManifestL0;
	selfSha256: string;
}

/** One unit as handed to {@link buildSplitManifest} (card text, not its digest). */
export interface SplitUnitInput {
	k: number;
	taskKey: string;
	ids: string[];
	budgetSum: number;
	slots: number;
	writeFace: string;
	/** Card body of this unit; `sha256` is derived from it, never supplied. */
	text: string;
}

/** Input of {@link buildSplitManifest}: the parsed claims plus the card bytes. */
export interface SplitManifestInput {
	parent: string;
	mode: "plan" | "on";
	/** Parent card text; `parentSha256` is derived from it. */
	parentText: string;
	/**
	 * Claim ids of the split, in canonical order. Must equal the unit id union in
	 * unit order — the manifest's `ids` is copied from here and is the merge
	 * gate's iteration order, so a silent reorder would reattribute verdicts.
	 */
	ids: string[];
	units: SplitUnitInput[];
	packing: SplitPackingRow[];
	l0: SplitManifestL0;
}

/** Optional evidence of {@link verifySplitManifest}: the live card texts. */
export interface SplitManifestVerifyContext {
	/** Parent card text, compared against `parentSha256` when present. */
	parentText?: string;
	/** Unit card texts keyed by `taskKey`, each compared against `units[*].sha256`. */
	unitTexts?: Record<string, string>;
}

/** The manifest without `selfSha256`: exactly the bytes `selfSha256` covers. */
type SplitManifestBody = Omit<SplitManifest, "selfSha256">;

/**
 * sha256 over the EOL-normalized UTF-8 bytes of `text`, lower-case hex.
 *
 * EOL-normalized: CRLF → LF on the bytes before hashing, the exact
 * `card_sha256` recipe (`shared/card-digest.ts::sha256EolNormalizedBytes`, the
 * TS mirror of `mw_common.sha256_eol_normalized`). So
 * `sha256Hex(text) === cardDigest(path)` for a file holding `text`, and a
 * checkout that flips line endings is not drift while a one-character content
 * edit is. Pure: no file access.
 */
export function sha256Hex(text: string): string {
	return sha256EolNormalizedBytes(new Uint8Array(Buffer.from(text, "utf8")));
}

/**
 * Rebuild the canonical manifest body. Every field is listed explicitly, in
 * declaration order, because `selfSha256` is `sha256(JSON.stringify(body))`:
 * an object spread would make the digest depend on the caller's key insertion
 * order instead of the schema's.
 */
function splitManifestBody(manifest: SplitManifest): SplitManifestBody {
	return {
		v: manifest.v,
		parent: manifest.parent,
		mode: manifest.mode,
		parentSha256: manifest.parentSha256,
		ids: manifest.ids,
		units: manifest.units.map((unit) => ({
			k: unit.k,
			taskKey: unit.taskKey,
			ids: unit.ids,
			budgetSum: unit.budgetSum,
			slots: unit.slots,
			writeFace: unit.writeFace,
			sha256: unit.sha256,
		})),
		packing: manifest.packing.map((row) => ({
			cluster: row.cluster,
			unit: row.unit,
			why: row.why,
		})),
		l0: {
			asks: manifest.l0.asks,
			mapped: manifest.l0.mapped,
			unmapped: manifest.l0.unmapped,
		},
	};
}

/**
 * The digest a manifest's `selfSha256` must carry ({@link sha256Hex} over the
 * serialized body). Exported so the merge gate can re-seal without rebuilding,
 * and so a test can state the recipe directly.
 */
export function splitManifestSelfSha256(manifest: SplitManifest): string {
	return sha256Hex(JSON.stringify(splitManifestBody(manifest)));
}

/** Throw on a programming error: a duplicate claim id in the unit id sets. */
function assertUniqueUnitIds(units: SplitUnitInput[]): void {
	const seen = new Set<string>();
	for (const unit of units) {
		for (const id of unit.ids) {
			if (seen.has(id)) {
				throw new Error(`split-manifest: duplicate claim id '${id}' in unit id sets`);
			}
			seen.add(id);
		}
	}
}

/**
 * Throw when `ids` is not exactly the concatenation of the unit id sets in unit
 * order. Order matters: `ids` is the merge gate's iteration order, so a silent
 * reorder would change which unit a verdict is attributed to.
 */
function assertIdSetMatchesUnits(ids: string[], units: SplitUnitInput[]): void {
	const union: string[] = [];
	for (const unit of units) union.push(...unit.ids);
	const sameLength = union.length === ids.length;
	const sameOrder = sameLength && union.every((id, index) => id === ids[index]);
	if (!sameOrder) {
		throw new Error(
			`split-manifest: ids must equal the unit id union in unit order (ids=${JSON.stringify(
				ids,
			)}, union=${JSON.stringify(union)})`,
		);
	}
}

/**
 * Build the split manifest, sealing every card text and the manifest body.
 *
 * `units[*].sha256 = sha256Hex(unit.text)`, `parentSha256 =
 * sha256Hex(parentText)`, `selfSha256 = sha256Hex(JSON.stringify(body))` — all
 * three EOL-normalized, so `parentSha256` equals the parent card's
 * `card_sha256:` header ({@link sha256Hex}). Throws (programming error, not
 * user input) when a claim id appears twice or when `ids` is not the unit id
 * union in unit order.
 */
export function buildSplitManifest(input: SplitManifestInput): SplitManifest {
	assertUniqueUnitIds(input.units);
	assertIdSetMatchesUnits(input.ids, input.units);

	const body: SplitManifestBody = {
		v: 1,
		parent: input.parent,
		mode: input.mode,
		parentSha256: sha256Hex(input.parentText),
		ids: [...input.ids],
		units: input.units.map((unit) => ({
			k: unit.k,
			taskKey: unit.taskKey,
			ids: [...unit.ids],
			budgetSum: unit.budgetSum,
			slots: unit.slots,
			writeFace: unit.writeFace,
			sha256: sha256Hex(unit.text),
		})),
		packing: input.packing.map((row) => ({
			cluster: [...row.cluster],
			unit: row.unit,
			why: row.why,
		})),
		l0: {
			asks: input.l0.asks,
			mapped: input.l0.mapped,
			unmapped: [...input.l0.unmapped],
		},
	};

	return {
		v: body.v,
		parent: body.parent,
		mode: body.mode,
		parentSha256: body.parentSha256,
		ids: body.ids,
		units: body.units,
		packing: body.packing,
		l0: body.l0,
		selfSha256: sha256Hex(JSON.stringify(body)),
	};
}

/**
 * Check a manifest against the live card texts and its own id bookkeeping.
 *
 * Returns the gap list, empty when the manifest is intact. NEVER throws: a
 * structurally broken manifest degrades to `split:manifest:self-sha` (its sha
 * chain cannot be reproduced), so the merge gate can refuse uniformly instead
 * of crashing on a hand-edited file. A card whose text the caller did not
 * supply is not a mismatch — presence of the child cards is the merge gate's
 * own check (design §2.4), not a digest check.
 *
 * Gap order: self-sha, parent-sha, unit-sha (unit order), id-set (missing then
 * extra, in encounter order), packing-unit (packing order, deduped).
 */
export function verifySplitManifest(manifest: SplitManifest, ctx: SplitManifestVerifyContext = {}): string[] {
	const gaps: string[] = [];
	try {
		if (splitManifestSelfSha256(manifest) !== manifest.selfSha256) {
			gaps.push("split:manifest:self-sha");
		}
		if (typeof ctx.parentText === "string" && sha256Hex(ctx.parentText) !== manifest.parentSha256) {
			gaps.push("split:manifest:parent-sha");
		}

		const unitTexts = ctx.unitTexts ?? {};
		for (const unit of manifest.units) {
			const text = unitTexts[unit.taskKey];
			if (typeof text === "string" && sha256Hex(text) !== unit.sha256) {
				gaps.push(`split:manifest:unit-sha:${unit.taskKey}`);
			}
		}

		// Union in unit order; a repeated id across units is reported as neither
		// missing nor extra (build already forbids it) — set membership decides.
		const union: string[] = [];
		const unionIds = new Set<string>();
		for (const unit of manifest.units) {
			for (const id of unit.ids) {
				if (unionIds.has(id)) continue;
				unionIds.add(id);
				union.push(id);
			}
		}
		const manifestIds = new Set(manifest.ids);
		for (const id of union) {
			if (!manifestIds.has(id)) gaps.push(`split:manifest:id-set:missing:${id}`);
		}
		for (const id of manifest.ids) {
			if (!unionIds.has(id)) gaps.push(`split:manifest:id-set:extra:${id}`);
		}

		const knownUnits = new Set(manifest.units.map((unit) => unit.k));
		const reportedUnits = new Set<number>();
		for (const row of manifest.packing) {
			if (knownUnits.has(row.unit) || reportedUnits.has(row.unit)) continue;
			reportedUnits.add(row.unit);
			gaps.push(`split:manifest:packing-unit:${row.unit}`);
		}
	} catch {
		// A manifest whose body cannot even be read has no reproducible sha chain.
		if (!gaps.includes("split:manifest:self-sha")) gaps.push("split:manifest:self-sha");
	}
	return gaps;
}

/**
 * Serialize a manifest as the on-disk artifact: canonical field order (the
 * schema order, independent of the caller's object construction), 2-space
 * indent, one trailing newline. `JSON.parse(serializeSplitManifest(m))` deep
 * equals `m`; the digest ride-along `selfSha256` is carried verbatim.
 */
export function serializeSplitManifest(manifest: SplitManifest): string {
	const body = splitManifestBody(manifest);
	const canonical: SplitManifest = {
		v: body.v,
		parent: body.parent,
		mode: body.mode,
		parentSha256: body.parentSha256,
		ids: body.ids,
		units: body.units,
		packing: body.packing,
		l0: body.l0,
		selfSha256: manifest.selfSha256,
	};
	return `${JSON.stringify(canonical, null, 2)}\n`;
}
