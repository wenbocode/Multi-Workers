"""Drift lock: the checked-in TS registry must equal a fresh render, byte for byte."""

from __future__ import annotations

import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent / "scripts"))  # noqa: E402
import gen_decide_registry_ts as gen  # noqa: E402

MW_ROOT = pathlib.Path(__file__).parent


def test_generated_registry_matches_a_fresh_render() -> None:
    path = gen.output_path()
    assert path.exists(), f"missing generated module: {gen.OUTPUT_RELATIVE_PATH}"
    on_disk = path.read_text(encoding="utf-8")
    assert on_disk == gen.render(), (
        "decide-registry.generated.ts is stale; run "
        "`cd packages/multi-workers && python scripts/gen_decide_registry_ts.py`"
    )


def test_generator_check_mode_is_clean() -> None:
    result = subprocess.run(
        [sys.executable, "scripts/gen_decide_registry_ts.py", "--check"],
        cwd=MW_ROOT,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    assert result.stdout == ""


def test_generated_header_and_shape_are_pinned() -> None:
    text = gen.output_path().read_text(encoding="utf-8")
    assert text.startswith(
        "// @generated by packages/multi-workers/scripts/gen_decide_registry_ts.py — do not edit\n"
    )
    assert "export const DECIDE_REGISTRY: Record<string, DecideRegistryEntry> = {" in text
    assert "export interface DecideRegistryEntry {" in text
    assert "\n\t\trequiredStateFields: [\n" in text


def test_rendered_entries_carry_the_registry_field_order() -> None:
    snapshot = gen.decision_points.registry_snapshot()
    text = gen.render(snapshot)
    for point in snapshot["points"]:
        assert f'\t"{point["id"]}": {{' in text
        fields = point.get("required_state_fields") or []
        positions = [text.index(f'name: "{field["name"]}"', text.index(f'"{point["id"]}": {{')) for field in fields]
        assert positions == sorted(positions), f"{point['id']}: field order drifted"


def test_rendered_context_slots_match_the_slot_table() -> None:
    import decision_context

    text = gen.output_path().read_text(encoding="utf-8")
    for dp_id in ("dp1-dispatch-type", "dp2-checkpoint-split", "dp3-worker-clarify"):
        expected = decision_context.slot_names_for(dp_id)
        rendered = ", ".join(f'"{slot}"' for slot in expected)
        assert f"contextSlots: [{rendered}]" in text
