"""T03-R2 stage probe: prove the old TS/stage locks blocked the successor card.

This is an in-process, synthetic demonstration, not T04 output and not a TS
build/parity check. It compares, on the *same* inputs:

1. the pre-R2 generated-TS assertions (dp1 required, no active id allowed) with
   the new stage-aware contract, using a synthetic eight-entry module string;
2. the old blanket "all eight unwired" assertion with the new backed-wiring
   contract, using one synthetic wired point;
3. the old exact ``by_dp == LEGACY_TS_ROWS`` equality with the new stage-aware
   rows contract, using a synthetic post-T04 required_if matrix.

Every synthetic input is written under this card's evidence dir (``fixture/``);
no product file is touched, no generator runs, no network/provider/decision CLI
is used. Usage: ``python probe_stage.py``.
"""

from __future__ import annotations

import copy
import json
import pathlib
import sys

EVIDENCE = pathlib.Path(__file__).resolve().parent
WORKTREE = EVIDENCE.parents[3] / "implementation-worktree"
PACKAGE = WORKTREE / "packages" / "multi-workers"
FIXTURE = EVIDENCE / "fixture"
sys.path.insert(0, str(PACKAGE))

import decision_points as dpts  # noqa: E402
import test_decide_registry_contract as contract  # noqa: E402

assert pathlib.Path(dpts.__file__).resolve().parent == PACKAGE
assert pathlib.Path(contract.__file__).resolve().parent == PACKAGE


def _outcome(fn, *args) -> dict:
    try:
        fn(*args)
    except AssertionError as err:
        return {"result": "rejected", "assertion": str(err)}
    return {"result": "accepted"}


def _synthetic_ts(ids: tuple[str, ...]) -> str:
    body = "".join(
        f'\t"{entry_id}": {{\n\t\tquestionsVersion: "q-synthetic",\n'
        "\t\trequiredStateFields: [\n\t\t\t{\n"
        '\t\t\t\tname: "task_goal",\n\t\t\t\ttype: "string",\n'
        '\t\t\t\tdescription: "synthetic",\n\t\t\t},\n\t\t],\n'
        "\t\toptionalStateFields: [],\n\t\tmodelStateFields: [],\n\t},\n"
        for entry_id in ids
    )
    return (
        "// @generated by packages/multi-workers/scripts/gen_decide_registry_ts.py "
        "(synthetic fixture, not generator output)\n"
        "export interface DecideRegistryEntry {\n\tid: string;\n}\n"
        "export const DECIDE_REGISTRY: Record<string, DecideRegistryEntry> = {\n"
        f"{body}}};\n"
    )


def _old_generated_ts_test(text: str) -> None:
    """Verbatim assertion body of the pre-R2 test (history, read-only)."""
    assert '"dp1-dispatch-type": {' in text, (
        "the generated TS changed unexpectedly; regeneration belongs to T04"
    )
    for entry_id in dpts.ACTIVE_DP_IDS:
        assert f'"{entry_id}": {{' not in text, (
            f"{entry_id}: generated TS was updated outside T04"
        )


def _old_all_unwired_test(points: list[dict]) -> None:
    """Verbatim assertion body of the pre-R2 all-unwired stage lock."""
    assert all(point["wired"] is False for point in points)


def _old_rows_test(by_dp: dict) -> None:
    """Verbatim assertion body of the pre-R2 legacy-row lock."""
    assert by_dp == contract.LEGACY_TS_ROWS, (
        "the legacy required_if matrix changed; only retired ids may keep a row: "
        f"{sorted(set(by_dp) - set(contract.LEGACY_TS_ROWS))}"
    )


def _wired_points(trigger: str) -> list[dict]:
    points = copy.deepcopy(contract._points())
    points[0]["wired"] = True
    points[0]["trigger"] = trigger
    points[0]["adopted_at"] = "2026-10-26T00:00:00Z"
    return points


def main() -> int:
    FIXTURE.mkdir(parents=True, exist_ok=True)
    results: dict = {"synthetic_only": True, "generator_run": False, "ts_build": False}

    post_t04 = FIXTURE / "eight-entry.synthetic.ts"
    post_t04.write_text(_synthetic_ts(contract.TARGET_EIGHT), encoding="utf-8")
    mixed = FIXTURE / "mixed-rename.synthetic.ts"
    mixed.write_text(
        _synthetic_ts(tuple(record.id for record in dpts.RETIRED_DP_REGISTRY)[1:] + ("dp-w-type",)),
        encoding="utf-8",
    )
    real_ts = contract.GENERATED_TS
    try:
        contract.GENERATED_TS = post_t04
        results["generated_ts"] = {
            "old_pre_r2_assertions": _outcome(_old_generated_ts_test, post_t04.read_text(encoding="utf-8")),
            "new_stage": contract._generated_ts_stage(),
            "new_contract": _outcome(contract.test_generated_ts_registry_is_the_frozen_legacy_or_the_t04_projection),
        }
        contract.GENERATED_TS = mixed
        results["one_sided_rename"] = {
            "new_stage": _outcome(contract._generated_ts_stage),
            "new_contract": _outcome(contract.test_generated_ts_registry_is_the_frozen_legacy_or_the_t04_projection),
        }
    finally:
        contract.GENERATED_TS = real_ts
    results["real_artifact_stage"] = contract._generated_ts_stage()

    backed = _wired_points("packages/multi-workers/decision_points.py:666")
    unbacked = _wired_points("packages/multi-workers/usage.py:1")
    real_points_fn = contract._points
    try:
        contract._points = lambda: backed
        results["wiring_backed"] = {
            "old_all_unwired_assertion": _outcome(_old_all_unwired_test, backed),
            "new_contract": _outcome(contract.test_wiring_claims_are_backed_by_the_call_site_they_cite),
        }
        contract._points = lambda: unbacked
        results["wiring_unbacked"] = {
            "new_contract": _outcome(contract.test_wiring_claims_are_backed_by_the_call_site_they_cite),
        }
    finally:
        contract._points = real_points_fn

    synthetic_rows = dict(contract.LEGACY_TS_ROWS)
    synthetic_rows["dp-sign-key"] = ["delivery_goal"]
    real_rows_fn = contract._ts_required_fields
    real_stage_fn = contract._generated_ts_stage
    try:
        contract._ts_required_fields = lambda: (["schema_version"], synthetic_rows)
        contract._generated_ts_stage = lambda: "post-t04"
        results["ts_rows_post_t04"] = {
            "old_exact_equality": _outcome(_old_rows_test, synthetic_rows),
            "new_contract": _outcome(contract.test_ts_required_rows_follow_the_registry_stage),
        }
    finally:
        contract._ts_required_fields = real_rows_fn
        contract._generated_ts_stage = real_stage_fn

    (EVIDENCE / "probe-stage.json").write_text(
        json.dumps(results, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(results, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
