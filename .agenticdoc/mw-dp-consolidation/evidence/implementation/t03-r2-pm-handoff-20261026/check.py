from pathlib import Path
import os
import sys
import json
import hashlib
import subprocess
from datetime import datetime, timezone

EVIDENCE = Path(__file__).resolve().parent
KEY = EVIDENCE.parents[2]
WORKTREE = KEY / 'implementation-worktree'
PACKAGE = WORKTREE / 'packages/multi-workers'
R2 = KEY / 'evidence/implementation/dpc-t03-protocol/rework-r2'

if len(sys.argv) > 1 and sys.argv[1] == 'probe':
    sys.path.insert(0, str(PACKAGE))
    import test_decide_registry_contract as contract
    import test_dp_consolidation_registry as examples
    import decision_points as dpts
    import mw
    for module in (contract, examples, dpts, mw):
        assert Path(module.__file__).resolve().parent == PACKAGE
    def result(fn):
        try:
            fn()
        except AssertionError as error:
            return {'outcome': 'rejected', 'detail': str(error)}
        return {'outcome': 'accepted'}
    probes = {'imports': {m.__name__: str(Path(m.__file__).resolve()) for m in (contract, examples, dpts, mw)}, 'synthetic_only': True, 'product_generation': False}
    roles = []
    times = []
    for dp in dpts.ACTIVE_DP_IDS:
        material = examples._material(dp)
        preparation = examples._preparation(dp, material)
        assert dpts.prepared_request_issues(dp, material, preparation, actor_role=dpts.ENTRY_ROLES[dp]) == ()
        absent = dpts.prepared_request_issues(dp, material, preparation)
        assert [path for path, detail in absent] == ['actor_role']
        roles.append({'dp': dp, 'absent': absent, 'legal_without_answer': []})
        bad = dict(preparation, prepared_at='not-an-ISO-timestamp')
        issues = dpts.preparation_issues(dp, bad, material)
        assert [path for path, detail in issues] == ['prepared_at']
        times.append({'dp': dp, 'invalid': issues})
    probes['roles'] = roles
    probes['times'] = times
    fixture = EVIDENCE / 'fixture/eight.synthetic.ts'
    fixture.parent.mkdir(parents=True, exist_ok=True)
    body = ''.join(f'\t"{dp}": {{\n\t\trequiredStateFields: [\n\t\t],\n\t}},\n' for dp in dpts.ACTIVE_DP_IDS)
    fixture.write_text('// @generated by packages/multi-workers/scripts/gen_decide_registry_ts.py synthetic fixture ONLY\nexport interface DecideRegistryEntry {}\nexport const DECIDE_REGISTRY: Record<string, DecideRegistryEntry> = {\n' + body + '};\n', encoding='utf-8')
    old_generated = contract.GENERATED_TS
    old_rows = contract._ts_required_fields
    try:
        contract.GENERATED_TS = fixture
        probes['eight_entry_shape'] = result(contract.test_generated_ts_registry_is_the_frozen_legacy_or_the_t04_projection)
        universal, _ = old_rows()
        active_only = {dp: list(dpts.REQUIRED_STATE_FIELDS[dp]) for dp in dpts.ACTIVE_DP_IDS}
        contract._ts_required_fields = lambda: (universal, active_only)
        probes['post_t04_active_only_matrix'] = result(contract.test_ts_required_rows_follow_the_registry_stage)
        # Same target through the real parser with a fixture peer, not a monkeypatch
        # of the extracted result. Preserve declaration syntax and identity block.
        peer = EVIDENCE / 'fixture/triage.active-only.synthetic.ts'
        universal_text = ', '.join(json.dumps(v) for v in universal)
        rows_text = ''.join('\t' + json.dumps(dp) + ': ' + json.dumps(fields) + ',\n' for dp, fields in active_only.items())
        peer.write_text('const UNIVERSAL_REQUIRED_FIELDS = [' + universal_text + '];\nexport const DP1_ID = "dp-w-type";\nexport const REQUIRED_FIELDS_BY_DP = {\n' + rows_text + '};\n', encoding='utf-8')
        contract._ts_required_fields = old_rows
        original_client = contract.TRIAGE_CLIENT
        try:
            contract.TRIAGE_CLIENT = peer
            probes['active_only_real_parser'] = result(contract.test_ts_required_rows_follow_the_registry_stage)
        finally:
            contract.TRIAGE_CLIENT = original_client
    finally:
        contract.GENERATED_TS = old_generated
        contract._ts_required_fields = old_rows
    probes['real_stage'] = contract._generated_ts_stage()
    (EVIDENCE / 'probe.json').write_text(json.dumps(probes, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(probes, ensure_ascii=False, indent=2))
    raise SystemExit(0)

manifest = json.loads((R2 / 'after-manifest.json').read_text(encoding='utf-8'))
handoff = json.loads((R2 / 'write-scope-check.json').read_text(encoding='utf-8'))['handoff']
checks = []
for record in manifest['files']:
    path = WORKTREE / record['path']
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    assert digest == record['sha256'], (record['path'], digest)
    assert data == (R2 / 'after-bytes' / Path(record['path']).name).read_bytes()
    checks.append({'path': record['path'], 'sha256': digest, 'bytes': len(data), 'crlf': data.count(b'\r\n'), 'bare_lf': data.count(b'\n') - data.count(b'\r\n')})
for relative, record in handoff.items():
    assert hashlib.sha256((WORKTREE / relative).read_bytes()).hexdigest() == record['after_sha256'], relative
home = EVIDENCE / 'fixture/home'
temp = EVIDENCE / 'fixture/temp'
project = EVIDENCE / 'fixture/project'
for path in (home, temp, project):
    path.mkdir(parents=True, exist_ok=True)
env = {k: os.environ[k] for k in ('PATH', 'SYSTEMROOT', 'SYSTEMDRIVE', 'WINDIR', 'COMSPEC', 'PATHEXT') if k in os.environ}
env.update({'HOME': str(home), 'USERPROFILE': str(home), 'APPDATA': str(home), 'LOCALAPPDATA': str(home), 'TEMP': str(temp), 'TMP': str(temp), 'TMPDIR': str(temp), 'PYTHONDONTWRITEBYTECODE': '1', 'PYTEST_DISABLE_PLUGIN_AUTOLOAD': '1', 'PYTHONIOENCODING': 'utf-8', 'PYTHONUTF8': '1'})
results = []
commands = [
    ('pm-green.log', [sys.executable, '-m', 'pytest', '-p', 'no:cacheprovider', '-q', 'test_decide_registry_contract.py', 'test_dp_consolidation_registry.py']),
    ('pm-probe.log', [sys.executable, str(Path(__file__).resolve()), 'probe']),
]
for label, argv in commands:
    completed = subprocess.run(argv, cwd=PACKAGE, env=env, capture_output=True, text=True, encoding='utf-8', errors='replace')
    log = f'cwd={PACKAGE}\nargv={argv}\nrc={completed.returncode}\nstdout:\n{completed.stdout}\nstderr:\n{completed.stderr}\n'
    (EVIDENCE / label).write_text(log, encoding='utf-8')
    print(log)
    results.append({'label': label, 'argv': argv, 'rc': completed.returncode})
result_doc = {'observed_at': datetime.now(timezone.utc).isoformat(), 'files': checks, 'handoff_paths_verified': len(handoff), 'tests': results, 'source_writes': False, 'semantic_handoff_verified': False, 'full_l2_verified': False}
(EVIDENCE / 'check.json').write_text(json.dumps(result_doc, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
assert all(row['rc'] == 0 for row in results)
